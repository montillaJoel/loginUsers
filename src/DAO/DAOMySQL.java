package src.DAO;

import src.utils.ConnectionDB;
import src.models.User;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;

/**
 * MySQL implementation of {@link DAOUser} that works with the {@code users} table.
 * <p>
 * In {@code insert} and the read methods, SQL errors are not thrown: their stack trace is printed
 * and the operation is skipped, so read methods return {@code null} or an empty list.
 * {@code update} and {@code delete} throw an {@link IllegalStateException} if the SQL fails or no
 * row matches, so the UI can tell the user.
 */
public class DAOMySQL implements DAOUser {

    /**
     * Inserts a new user. The database generates the ID (AUTO_INCREMENT),
     * and it is then set on the given user object.
     *
     * @param u the user to insert
     */
    @Override
    public void insert(User u) {
        String sql = "INSERT INTO users (name, last_name, phone_number, email, user_name, hash_key) VALUES (?, ?, ?, ?, ?, ?)";
        try (Connection con = ConnectionDB.open();
             PreparedStatement ps = con.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            ps.setString(1, u.getName());
            ps.setString(2, u.getLastName());
            ps.setString(3, u.getPhoneNumber());
            ps.setString(4, u.getEmail());
            ps.setString(5, u.getUserName());
            ps.setString(6, u.getHashKey());
            ps.executeUpdate();

            // Store the ID generated by the database in the user object
            try (ResultSet keys = ps.getGeneratedKeys()) {
                if (keys.next()) {
                    u.setId(keys.getInt(1));
                }
            }
        } catch (SQLException e) {
            e.printStackTrace();
        }
    }

    @Override
    public User getById(int id) {
        String sql = "SELECT * FROM users WHERE id = ?";
        User u = null;
        try (Connection con = ConnectionDB.open();
             PreparedStatement ps = con.prepareStatement(sql)) {
            ps.setInt(1, id);
            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    u = new User(rs.getString("name"),
                            rs.getString("last_name"), rs.getString("phone_number"),
                            rs.getString("email"), rs.getString("user_name"),
                            rs.getString("hash_key"));
                    u.setId(rs.getInt("id"));
                }
            }
        } catch (SQLException e) {
            e.printStackTrace();
        }
        return u;
    }

    @Override
    public List<User> getAll() {
        String sql = "SELECT * FROM users";
        List<User> lista = new ArrayList<>();
        try (Connection con = ConnectionDB.open();
             Statement st = con.createStatement();
             ResultSet rs = st.executeQuery(sql)) {
            while (rs.next()) {
                User u = new User(rs.getString("name"),
                    rs.getString("last_name"), rs.getString("phone_number"),
                    rs.getString("email"), rs.getString("user_name"),
                    rs.getString("hash_key"));
                u.setId(rs.getInt("id"));
                lista.add(u);
            }
        } catch (SQLException e) {
            e.printStackTrace();
        }
        return lista;
    }

    @Override
    public void update(User u) {
        String sql = "UPDATE users SET name = ?, last_name = ?, phone_number = ?, email = ?, user_name = ?, hash_key = ? WHERE id = ?";
        try (Connection con = ConnectionDB.open();
             PreparedStatement ps = con.prepareStatement(sql)) {
            ps.setString(1, u.getName());
            ps.setString(2, u.getLastName());
            ps.setString(3, u.getPhoneNumber());
            ps.setString(4, u.getEmail());
            ps.setString(5, u.getUserName());
            ps.setString(6, u.getHashKey());
            ps.setInt(7, u.getId());
            if (ps.executeUpdate() == 0) {
                throw new IllegalStateException("No se encontró el usuario con ID " + u.getId() + ".");
            }
        } catch (SQLException e) {
            throw new IllegalStateException("No se pudo actualizar el usuario: " + e.getMessage(), e);
        }
    }

    @Override
    public void delete(int id) {
        String sql = "DELETE FROM users WHERE id = ?";
        try (Connection con = ConnectionDB.open();
             PreparedStatement ps = con.prepareStatement(sql)) {
            ps.setInt(1, id);
            if (ps.executeUpdate() == 0) {
                throw new IllegalStateException("No se encontró el usuario con ID " + id + ".");
            }
        } catch (SQLException e) {
            throw new IllegalStateException("No se pudo eliminar el usuario: " + e.getMessage(), e);
        }
    }
}